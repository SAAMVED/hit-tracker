CREATE TABLE users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('commander','viewer')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE teams (
  id TEXT PRIMARY KEY,
  name TEXT,
  metadata JSONB NOT NULL DEFAULT '{}'::jsonb
);
CREATE TABLE soldiers (
  id TEXT PRIMARY KEY,
  name TEXT,
  metadata JSONB NOT NULL DEFAULT '{}'::jsonb
);
CREATE TABLE missions (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  started_at TIMESTAMPTZ NOT NULL,
  ended_at TIMESTAMPTZ,
  status TEXT NOT NULL CHECK (status IN ('active','completed')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX missions_started_idx ON missions(started_at DESC);
CREATE TABLE mission_soldiers (
  mission_id TEXT NOT NULL REFERENCES missions(id) ON DELETE CASCADE,
  soldier_id TEXT NOT NULL REFERENCES soldiers(id),
  team_id TEXT NOT NULL REFERENCES teams(id),
  assigned_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY(mission_id,soldier_id,team_id)
);
CREATE INDEX mission_soldiers_team_idx ON mission_soldiers(team_id,mission_id);
CREATE TABLE telemetry (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mission_id TEXT NOT NULL REFERENCES missions(id),
  soldier_id TEXT NOT NULL REFERENCES soldiers(id),
  team_id TEXT NOT NULL REFERENCES teams(id),
  seq BIGINT NOT NULL,
  timestamp TIMESTAMPTZ NOT NULL,
  x DOUBLE PRECISION NOT NULL,
  y DOUBLE PRECISION NOT NULL,
  latitude DOUBLE PRECISION,
  longitude DOUBLE PRECISION,
  altitude DOUBLE PRECISION,
  floor TEXT,
  floor_metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
  pressure_hpa DOUBLE PRECISION NOT NULL,
  differential_pressure_hpa DOUBLE PRECISION,
  battery_pct SMALLINT NOT NULL CHECK (battery_pct BETWEEN 0 AND 100),
  signal_strength SMALLINT NOT NULL,
  sensor_metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
  received_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (latitude IS NULL OR latitude BETWEEN -90 AND 90),
  CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180)
);
CREATE INDEX telemetry_mission_soldier_time_idx ON telemetry(mission_id,soldier_id,timestamp,id);
CREATE INDEX telemetry_mission_time_idx ON telemetry(mission_id,timestamp,id);
CREATE INDEX telemetry_soldier_time_idx ON telemetry(soldier_id,timestamp DESC);
CREATE INDEX telemetry_team_time_idx ON telemetry(team_id,timestamp DESC);
CREATE TABLE alerts (
  id TEXT PRIMARY KEY,
  type TEXT NOT NULL,
  severity TEXT NOT NULL CHECK (severity IN ('info','warning','critical')),
  soldier_id TEXT NOT NULL REFERENCES soldiers(id),
  team_id TEXT NOT NULL REFERENCES teams(id),
  mission_id TEXT REFERENCES missions(id),
  message TEXT NOT NULL,
  ts TIMESTAMPTZ NOT NULL,
  acknowledged BOOLEAN NOT NULL DEFAULT false,
  acknowledged_by TEXT,
  acknowledged_at TIMESTAMPTZ,
  payload JSONB NOT NULL DEFAULT '{}'::jsonb
);
CREATE INDEX alerts_mission_time_idx ON alerts(mission_id,ts DESC);
CREATE INDEX alerts_soldier_time_idx ON alerts(soldier_id,ts DESC);
CREATE TABLE calibration (
  id TEXT PRIMARY KEY,
  translation_x NUMERIC NOT NULL DEFAULT 0,
  translation_y NUMERIC NOT NULL DEFAULT 0,
  translation_z NUMERIC NOT NULL DEFAULT 0,
  rotation_x NUMERIC NOT NULL DEFAULT 0,
  rotation_y NUMERIC NOT NULL DEFAULT 0,
  rotation_z NUMERIC NOT NULL DEFAULT 0,
  scale_x NUMERIC NOT NULL DEFAULT 1,
  scale_y NUMERIC NOT NULL DEFAULT 1,
  scale_z NUMERIC NOT NULL DEFAULT 1,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE calibration_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  calibration_id TEXT NOT NULL REFERENCES calibration(id),
  translation_x NUMERIC NOT NULL,
  translation_y NUMERIC NOT NULL,
  translation_z NUMERIC NOT NULL,
  rotation_x NUMERIC NOT NULL,
  rotation_y NUMERIC NOT NULL,
  rotation_z NUMERIC NOT NULL,
  scale_x NUMERIC NOT NULL,
  scale_y NUMERIC NOT NULL,
  scale_z NUMERIC NOT NULL,
  changed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  changed_by TEXT
);
CREATE TABLE reference_readings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  station_id TEXT NOT NULL,
  pressure_hpa DOUBLE PRECISION NOT NULL,
  temperature_c DOUBLE PRECISION,
  timestamp TIMESTAMPTZ NOT NULL DEFAULT now(),
  metadata JSONB NOT NULL DEFAULT '{}'::jsonb
);
CREATE INDEX reference_time_idx ON reference_readings(timestamp DESC);
CREATE TABLE rejected_packets (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  soldier_id TEXT,
  reason TEXT NOT NULL,
  raw_payload JSONB NOT NULL,
  timestamp TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX rejected_time_idx ON rejected_packets(timestamp DESC);
CREATE INDEX rejected_soldier_time_idx ON rejected_packets(soldier_id,timestamp DESC);
CREATE TABLE building_models (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  file_path TEXT NOT NULL UNIQUE,
  content_type TEXT NOT NULL DEFAULT 'model/gltf-binary',
  checksum TEXT,
  metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE mission_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mission_id TEXT NOT NULL REFERENCES missions(id) ON DELETE CASCADE,
  event_type TEXT NOT NULL,
  occurred_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  payload JSONB NOT NULL DEFAULT '{}'::jsonb
);
CREATE INDEX mission_events_time_idx ON mission_events(mission_id,occurred_at);
CREATE TABLE import_runs (
  source_fingerprint TEXT PRIMARY KEY,
  source_path TEXT NOT NULL,
  counts JSONB NOT NULL,
  imported_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
